def info(table):
    enums, rules, unique = {}, [], {}
    for c in table.constraints:
        if isinstance(c, CheckConstraint):
            text = str(c.sqltext)
            m = re.fullmatch(r"(\w+) IN \((.*)\)", text)
            if m:
                enums[m.group(1)] = m.group(2).replace("'", "")
            else:
                rules.append(text)
        elif isinstance(c, UniqueConstraint):
            names = [col.name for col in c.columns]
            for n in names:
                unique[n] = "unique together with (" + ", ".join(names) + ")"
    return enums, rules, unique


def row(table, col, enums, rules, unique):
    fks = list(col.foreign_keys)
    key = " ".join(x for x in ("PK" if col.primary_key else "", f"FK -> {fks[0].column}" if fks else "") if x) or "-"
    if col.primary_key and len(table.primary_key.columns) == 1:
        uniq = "unique (primary key)"
    elif col.primary_key:
        uniq = "unique together with the other key columns"
    else:
        uniq = unique.get(col.name, "-")
    checks = []
    if col.primary_key and table.name in ID_FORMATS:
        checks.append(f"format {ID_FORMATS[table.name]}")
    if col.name.endswith("_date") or col.name in ("date_of_birth", "effective_from"):
        checks.append("ISO date YYYY-MM-DD")
    if col.name.endswith("_at") or col.name == "event_time":
        checks.append("ISO-8601 UTC timestamp")
    if fks:
        checks.append("must exist in the parent table")
    checks += [r for r in rules if re.search(rf"\b{col.name}\b", r)]
    if (table.name, col.name) in NOTES:
        checks.append(NOTES[(table.name, col.name)])
    derived = table.name in DERIVED_TABLES or (table.name, col.name) in DERIVED_COLUMNS
    cells = [col.name, str(col.type), "yes" if not col.nullable else "no", key, enums.get(col.name, "-"),
             "INR cents (integer)" if col.name.endswith("_cents") else "-", uniq, "; ".join(checks) or "-",
             "derived" if derived else "source"]
    return "| " + " | ".join(c.replace("|", "\\|") for c in cells) + " |"


def main() -> None:
    meta = database.metadata.tables
    out = ["# Data dictionary", "", "Generated by `python scripts/build_docs.py` from the real database schema.", "",
           "Amounts are integer cents of INR. Dates are ISO text (`YYYY-MM-DD`). "
           "Required = NOT NULL. Source = generated or entered; derived = computed from other records.", ""]
    for title, name in ENTITIES + SUPPORT:
        table = meta[name]
        enums, rules, unique = info(table)
        out += [f"## {title} (`{name}`)", "",
                "| Field | Type | Required | Key | Allowed values | Unit | Uniqueness | Validation | Source / derived |",
                "|---|---|---|---|---|---|---|---|---|"]
        out += [row(table, col, enums, rules, unique) for col in table.columns]
        out.append("")
    docs = config.ROOT_DIR / "docs"
    docs.mkdir(exist_ok=True)
    (docs / "data_dictionary.md").write_text("\n".join(out), encoding="utf-8")

    fk_lines = [f"| {t.name}.{fk.parent.name} | {fk.column.table.name}.{fk.column.name} |"
                for t in database.metadata.sorted_tables for fk in sorted(t.foreign_keys, key=lambda f: f.parent.name)]
    schema = ["# Schema, keys and cardinalities", "",
              "## Foreign keys (enforced by the database; SQLite runs with `PRAGMA foreign_keys=ON`)", "",
              "| Child column | Parent column |", "|---|---|", *fk_lines, "",
              "## Cardinalities", "",
              "| Relationship | Cardinality | Mandatory? | Notes |", "|---|---|---|---|",
              "| Claimant - Policy | 1:N | policy must have a claimant | a claimant may hold several policies |",
              "| Policy - Claim | 1:N | claim must have a policy | claims on a nonexistent policy are quarantined |",
              "| Claimant - Claim | 1:N | mandatory | claimant must match the policy holder (validated) |",
              "| Incident - Claim | 1:N allowed by schema | mandatory | this generator makes it 1:1 |",
              "| Claim - Invoice | 1:N | optional | invoice totals must equal the claimed amount |",
              "| Provider - Invoice | 1:N | mandatory | Claim - Provider is N:M through invoices |",
              "| Invoice - Payment | 1:N | optional | payments per claim must not exceed the approved amount (exceptions are labelled) |",
              "| Claim - status events | 1:N | at least SUBMITTED | append-only history; claims.status mirrors the latest event |",
              "| Detection run - Indicator | 1:N | mandatory | old runs are kept |",
              "| Investigation - Indicator | N:M | optional | bridge table investigation_indicators |",
              "| Investigation - events | 1:N | at least OPENED | append-only |",
              "| Investigation - subject | 1 per (subject_type, subject_id) | mandatory | UNIQUE constraint |",
              "| RelationshipEdge endpoints | N:M between entities | mandatory | polymorphic, validated in code; effective_from gives the start date |", "",
              "## Lifecycles", "",
              "- Claim: SUBMITTED -> UNDER_REVIEW -> APPROVED or REJECTED; APPROVED -> PARTIALLY_PAID -> PAID (or APPROVED -> PAID).",
              "- Policy: ACTIVE, EXPIRED (end date passed) or CANCELLED.",
              "- Investigation: OPEN -> IN_REVIEW -> ESCALATED / CLOSED_NO_ACTION / CLOSED_ACTION_TAKEN; closed states are final.", ""]
    (docs / "schema.md").write_text("\n".join(schema), encoding="utf-8")
    print("Wrote docs/data_dictionary.md and docs/schema.md")


if __name__ == "__main__":
    main()